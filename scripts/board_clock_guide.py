"""Render the board clock guide table from the Lean chip manifest.

The table in docs/board-clock-guide.md sits between two markers and is
generated, never edited by hand. `--check` exits 1 when the committed table
differs from what the manifest says.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = ROOT / 'build/chip-manifest/streaming-ready-d2.json'
DOC = ROOT / 'docs/board-clock-guide.md'
START = '<!-- board-clock-guide:start (generated by scripts/board_clock_guide.py) -->'
END = '<!-- board-clock-guide:end -->'

NAMES = {'uart_rx': 'UART receive', 'spi': 'SPI', 'jtag': 'JTAG', 'i2c': 'I²C',
         'can_receive': 'CAN receive', 'ps2_receive': 'PS/2 receive', 'ethernet_sni_tx': 'Ethernet SNI transmit'}
MODES = {'standard': 'standard', 'fast': 'Fast', 'fast_plus': 'Fast-mode Plus'}


def mhz(hz):
    return f'{hz / 1e6:g} MHz'


def describe(row):
    setting, result = row['setting'], row['result']
    program = row['program']
    if program == 'uart_rx':
        text = f"{setting['baud']} baud, `quarter_cycles={setting['quarter_cycles']}`"
        outcome = (f"bit = {result['bit_core_clocks']} core clocks; every sample point lands in its bit"
                   if row['usable'] else 'needs `quarter_cycles` above the limit of 128')
    elif program in ('spi', 'jtag'):
        text = f"`half_cycles={setting['half_cycles']}`"
        outcome = (f"bit clock up to {result['max_clock_hz']:,} Hz; peer output delay at most "
                   f"{result['peer_output_window_ns']} ns")
    elif program == 'i2c':
        text = (f"`low_cycles={setting['low_cycles']}`, `high_cycles={setting['high_cycles']}`, "
                f"`wait_budget={setting['wait_budget']}`")
        modes = ', '.join(MODES[m] for m in row['meets']) or 'no I²C mode'
        outcome = f"meets {modes}; clock stretch up to {result['stretch_tolerance_core_clocks']} core clocks"
    else:
        text = 'fixed image'
        outcome = f"needs a {mhz(result['required_core_hz'])} core clock"
    return text, outcome


def render(manifest):
    lines = ['| Board clock | Example | Setting | What it gives | Usable |', '| --- | --- | --- | --- | --- |']
    for row in manifest['board_clock_guide']:
        text, outcome = describe(row)
        lines.append(f"| {mhz(row['core_hz'])} | {NAMES[row['program']]} | {text} | {outcome} | "
                     f"{'yes' if row['usable'] else 'no'} |")
    return '\n'.join(lines)


def splice(doc, table):
    before, rest = doc.split(START, 1)
    _, after = rest.split(END, 1)
    return before + START + '\n' + table + '\n' + END + after


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--manifest', type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument('--check', action='store_true', help='fail if the committed table is stale')
    args = parser.parse_args(argv)
    manifest = json.loads(args.manifest.read_text())
    current = DOC.read_text()
    wanted = splice(current, render(manifest))
    if args.check:
        if wanted != current:
            print('docs/board-clock-guide.md is out of date; run scripts/board_clock_guide.py')
            return 1
        print('docs/board-clock-guide.md matches the manifest')
        return 0
    DOC.write_text(wanted)
    print('wrote docs/board-clock-guide.md')
    return 0


if __name__ == '__main__':
    sys.exit(main())
